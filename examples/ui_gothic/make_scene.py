# tabs and bars
for i, (name, active) in enumerate((("Heroes", True), ("Items", False), ("Quests", False))):
    piece = "tab_active" if active else "tab_inactive"
    L.append(f'    node Tab{name} {{ position = [{520 + i * 120}, 650]  UITransform {{ size = [116, 46] }}  {sprite(piece, 116, 46)}  '
             f'node T {{ position = [0, 4]  UITransform {{ size = [110, 40] }}  Label {{ text = "{name}"  size = 20  align = "center"  valign = "middle"  color = [245, 230, 200, 255] }} }} }}')
for i, kind in enumerate(("hp", "mana", "xp")):
    L.append(f"    node Bar_{kind} {{ position = [{150}, {630 + i * 26}]  UITransform {{ size = [220, 24] }}  {sprite('bar_frame', 220, 24)}  "
             f"node Fill {{ position = [{-110 + 110 * (0.9 - 0.25 * i) - 2}, 0]  UITransform {{ size = [{220 * (0.9 - 0.25 * i)}, 24] }}  {sprite('bar_fill_' + kind, round(220 * (0.9 - 0.25 * i)), 24)} }} }}")
L += ["  }", "}"]
(HERE / "assets" / "scenes").mkdir(parents=True, exist_ok=True)
(HERE / "assets" / "scenes" / "ui.scene").write_text("\n".join(L) + "\n", encoding="utf-8")
meta = HERE / "assets" / "scenes" / "ui.scene.meta"
if not meta.exists():
    meta.write_text("id: 7e3f0a31\nkind: scene\nversion: 1\n")
print("scenes/ui.scene written")

