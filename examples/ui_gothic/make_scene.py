"""Regenerate the gothic UI example: the kit (tools/gen_gothic_ui.py) and scenes/ui.scene from its ui_kit.json.

    python examples/ui_gothic/make_scene.py [--palette crimson|royal|emerald|bone]
"""
import argparse
import json
import pathlib
import subprocess
import sys

HERE = pathlib.Path(__file__).resolve().parent
VELO = HERE.parents[1]

ap = argparse.ArgumentParser()
ap.add_argument("--palette", default="crimson")
a = ap.parse_args()
kit_dir = HERE / "assets" / "ui" / "gothic"
subprocess.run([sys.executable, str(VELO / "tools" / "gen_gothic_ui.py"), str(kit_dir), "--palette", a.palette,
                "--check"], check=True)
kit = json.loads((kit_dir / "ui_kit.json").read_text())
K = kit["scale"]  # texture pixels per design unit
P = kit["pieces"]


def sprite(piece, w, h, extra=""):
    p = P[piece]
    f = [f'texture = @asset("ui/gothic/{piece}.png")', 'draw_mode = "sliced"', f"size = [{w}, {h}]",
         f"pixel_scale = {1 / K:g}"]
    for k in ("left", "top", "right", "bottom"):
        f.append(f"border_{k} = {p[k]}")
    for k in ("ornament_x", "ornament_y"):
        if k in p:
            f.append(f"{k} = [{p[k][0]}, {p[k][1]}]")
    return "Sprite { " + "  ".join(f) + (("  " + extra) if extra else "") + " }"


def button(name, x, y, w, h, kind, text, icon=True, disabled=False):
    st = lambda s: f'@asset("ui/gothic/button_{kind}_{s}.png")'
    lines = [f"    node {name} {{",
             f"      position = [{x}, {y}]",
             f"      UITransform {{ size = [{w}, {h}] }}",
             "      " + sprite(f"button_{kind}", w, h),
             f"      Button {{ hover_sprite = {st('hover')}  pressed_sprite = {st('pressed')}  disabled_sprite = {st('disabled')}"
             f"  hover_scale = 1.05  pressed_scale = 0.95  hover_glow = [255, 220, 150, 40]"
             f"  normal_color = [255, 255, 255, 255]  hover_color = [255, 255, 255, 255]  pressed_color = [255, 255, 255, 255]"
             f"  disabled_color = [255, 255, 255, 255]{'  interactable = false' if disabled else ''} }}",
             # icon + text as one group, centred on the plate whatever the text length
             "      node Content {",
             "        UITransform { size = [10, 10] }",
             '        Layout { kind = "horizontal"  spacing = [10, 0]  child_align = "center"  resize = true }']
    if icon:
        lines.append('        node Icon { UITransform { size = [26, 26] }  Sprite { texture = @asset("sprites/sparkle.png")  size = [26, 26]  draw_mode = "fit" } }')
    lines.append(f'        node Text {{ UITransform {{ size = [10, {h - 16}] }}  Label {{ text = "{text}"  size = 24  align = "center"  valign = "middle"  auto_size = true  color = [255, 240, 210, 255]  outline_color = [20, 8, 10, 255]  outline_width = 2 }} }}')
    lines += ["      }", "    }"]
    return lines


